form.addEventListener("submit", async (event) => {
  event.preventDefault();
  const t = I18N[currentLang()];

  if (!inboxReady()) {
    showStatus("err", t.needEmail);
    return;
  }

  if (!form.reportValidity()) {
    showStatus("err", t.required);
    return;
  }

  const workFile = workInput.files[0];
  const workLink = String(form.workLink.value || "").trim();
  if (!workFile && !workLink) {
    showStatus("err", t.needWork);
    form.workLink.focus();
    return;
  }

  if (workFile) {
    const workIssue = await fileProblem(workFile, "work");
    if (workIssue) {
      showStatus("err", t[workIssue]);
      return;
    }
  }

  const cvFile = cvInput.files[0];
  if (cvFile) {
    const cvIssue = await fileProblem(cvFile, "cv");
    if (cvIssue) {
      showStatus("err", t[cvIssue]);
      return;
    }
  }

  submitBtn.disabled = true;
  submitBtn.textContent = t.sending;

  const honey = form.querySelector('[name="_honey"]');
  if (honey) honey.value = "";

  let workDl = workLink;
  let cvLink = "";
  try {
    if (workFile) {
      const uploaded = await uploadFile(workFile);
      if (uploaded) workDl = uploaded;
    }
    if (cvFile) cvLink = await uploadFile(cvFile);
  } catch (_) {
    /* still send the rest of the form */
  }

  const stay = window.setTimeout(() => {
    if (!submitBtn.disabled) return;
    resetSendButton();
    showStatus("err", t.netErr);
  }, 18000);

  try {
    const code = makeMarketerCode();
    postToInbox({
      fullName: form.fullName.value,
      email: form.email.value,
      phone: form.phone.value,
      message: applicationMessage({ code, workFile, cvFile, workDl, cvLink }),
    });
  } catch (_) {
    window.clearTimeout(stay);
    resetSendButton();
    showStatus("err", t.netErr);
  }
});
